export class CatalogoDeIdioma {
  constructor(readonly idioma: Idioma) {}

  traduzir(texto: string): string {
    if (this.idioma === 'pt-BR') return texto;
    const opcoes = mensagens[texto.trim()];
    if (!opcoes) return texto;
    return texto.replace(texto.trim(), () => opcoes[this.idioma === 'en' ? 0 : 1]);
  }
}
